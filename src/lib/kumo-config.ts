export type ServerConfig = {
  max_connections: number;
  max_message_rate: string; // e.g. "100/min"
  enable_tls: "Opportunistic" | "OpportunisticInsecure" | "Required";
  sending: boolean;
};
export const DEFAULT_CONFIG: ServerConfig = { max_connections: 32, max_message_rate: "300/min", enable_tls: "OpportunisticInsecure", sending: true };
export function parseConfig(v: unknown): ServerConfig {
  const o = (v && typeof v === "object" ? v : {}) as Partial<ServerConfig>;
  const rate = typeof o.max_message_rate === "string" && /^\d+\/(s|sec|min|h|hr|day)$/.test(o.max_message_rate) ? o.max_message_rate : DEFAULT_CONFIG.max_message_rate;
  const conns = Number(o.max_connections);
  return {
    max_connections: Number.isFinite(conns) && conns >= 1 && conns <= 1000 ? Math.floor(conns) : DEFAULT_CONFIG.max_connections,
    max_message_rate: rate,
    enable_tls: o.enable_tls === "Opportunistic" || o.enable_tls === "Required" ? o.enable_tls : "OpportunisticInsecure",
    sending: o.sending !== false,
  };
}

const lua = (s: string) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

/** Generates /opt/kumomta/etc/policy/init.lua. Injection API stays on localhost; events go to Cortex. */
export function buildInitLua(o: { hostname: string; eventsUrl: string; cfg: ServerConfig; relay?: { host: string; username: string; password: string } | null }) {
  const egress = [
    `enable_tls = ${lua(o.relay ? "Required" : o.cfg.enable_tls)}`,
    `max_connections = ${o.cfg.max_connections}`,
    `max_message_rate = ${lua(o.cfg.max_message_rate)}`,
    `ehlo_domain = ${lua(o.hostname)}`,
    ...(o.relay ? ["smtp_port = 587", `smtp_auth_plain_username = ${lua(o.relay.username)}`, `smtp_auth_plain_password = { key_data = ${lua(o.relay.password)} }`] : []),
  ].join(",\n    ");
  return `-- Generated by Cortex. Changes made here are overwritten by "Apply Cortex config".
local kumo = require 'kumo'
local log_hooks = require 'policy-extras.log_hooks'

log_hooks:new_json {
  name = 'cortex',
  url = ${lua(o.eventsUrl)},
  log_parameters = { headers = { 'X-Cortex-Job' } },
}

kumo.on('init', function()
  kumo.define_spool { name = 'data', path = '/var/spool/kumomta/data', kind = 'RocksDB' }
  kumo.define_spool { name = 'meta', path = '/var/spool/kumomta/meta', kind = 'RocksDB' }
  kumo.configure_local_logs { log_dir = '/var/log/kumomta', max_segment_duration = '1 minute' }
  kumo.configure_bounce_classifier { files = { '/opt/kumomta/share/bounce_classifier/iana.toml' } }
  -- Injection and admin API: localhost only, used by the Cortex agent.
  kumo.start_http_listener { listen = '127.0.0.1:8000', trusted_hosts = { '127.0.0.1', '::1' } }
end)

kumo.on('get_egress_path_config', function(domain, egress_source, site_name)
  return kumo.make_egress_path {
    ${egress}
  }
end)
${o.relay ? `
kumo.on('get_queue_config', function(domain, tenant, campaign, routing_domain)
  return kumo.make_queue_config {
    protocol = { smtp = { mx_list = { ${lua(o.relay.host)} } } },
  }
end)
` : ""}`;
}

/** A server counts as online when its agent reported within the last 90 seconds. */
export function isOnline(lastSeen: string | null | undefined, now = Date.now()) {
  return !!lastSeen && now - new Date(lastSeen).getTime() < 90_000;
}

/** Messages a server may take in one 10-second agent poll. */
export function pollQuota(o: { sendSpeedPerHour: number; minuteLimit: number; batchSize: number; onlineServers: number; sentToday: number; dailyLimit: number | null }) {
  if (o.dailyLimit && o.sentToday >= o.dailyLimit) return 0;
  const perMinute = Math.min(o.minuteLimit || Infinity, Math.max(1, o.sendSpeedPerHour) / 60);
  let n = Math.ceil(perMinute / 6 / Math.max(1, o.onlineServers));
  n = Math.min(n, o.batchSize || 100, 500);
  if (o.dailyLimit) n = Math.min(n, o.dailyLimit - o.sentToday);
  return Math.max(0, n);
}

/** Parses bulk lines: "name,ip[,pool]" or just "ip". */
export function parseBulkServers(text: string) {
  const ipRe = /^(\d{1,3}\.){3}\d{1,3}$|^[0-9a-f:]+:[0-9a-f:]*$/i;
  return text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean).map((l) => {
    const parts = l.split(/[,;\t ]+/).filter(Boolean);
    const ip = parts.find((p) => ipRe.test(p)) ?? "";
    const rest = parts.filter((p) => p !== ip);
    return { ip, name: rest[0] || ip, pool: rest[1] || "default", valid: ipRe.test(ip) };
  });
}
